// 名词随数量取形：个位 1（11 除外）取单数，个位 2–4（12–14 除外）取少数，其余取多数。
function plural(count: number, one: string, few: string, many: string): string {
  const mod10 = count % 10
  const mod100 = count % 100
  if (mod10 === 1 && mod100 !== 11)
    return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14))
    return few
  return many
}

function text(value: unknown): string {
  return issueParam(value, ', ')
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`не меньше ${text(params.min)}`)
  if (params.exclusiveMin !== undefined)
    parts.push(`больше ${text(params.exclusiveMin)}`)
  if (params.max !== undefined)
    parts.push(`не больше ${text(params.max)}`)
  return parts.length === 0 ? 'Значение вне допустимого диапазона' : `Должно быть ${parts.join(' и ')}`
}

