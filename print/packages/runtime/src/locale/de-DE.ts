const REGION_NAMES = { header: 'Kopfzeile', body: 'Hauptteil', footer: 'Fußzeile' } as const

function text(value: unknown): string {
  return issueParam(value, ', ')
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`mindestens ${text(params.min)}`)
  if (params.exclusiveMin !== undefined)
    parts.push(`größer als ${text(params.exclusiveMin)}`)
  if (params.max !== undefined)
    parts.push(`höchstens ${text(params.max)}`)
  return parts.length === 0 ? 'Außerhalb des zulässigen Bereichs' : `Muss ${parts.join(' und ')} sein`
}

