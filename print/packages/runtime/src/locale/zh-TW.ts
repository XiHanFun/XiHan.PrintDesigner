const REGION_NAMES = { header: '頁首', body: '內文', footer: '頁尾' } as const

function text(value: unknown): string {
  return issueParam(value, '、')
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`不小於 ${text(params.min)}`)
  if (params.exclusiveMin !== undefined)
    parts.push(`大於 ${text(params.exclusiveMin)}`)
  if (params.max !== undefined)
    parts.push(`不大於 ${text(params.max)}`)
  return parts.length === 0 ? '超出範圍' : `應${parts.join('、')}`
}

