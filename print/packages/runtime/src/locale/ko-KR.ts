function text(value: unknown): string {
  return issueParam(value, ', ')
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`${text(params.min)} 이상`)
  if (params.exclusiveMin !== undefined)
    parts.push(`${text(params.exclusiveMin)} 초과`)
  if (params.max !== undefined)
    parts.push(`${text(params.max)} 이하`)
  if (parts.length === 0)
    return '범위를 벗어났습니다'
  const ending = params.max === undefined && params.exclusiveMin === undefined ? '이어야' : '여야'
  return `${parts.join(' ')}${ending} 합니다`
}

