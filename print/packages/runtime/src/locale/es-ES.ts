const REGION_NAMES = { header: 'Encabezado', body: 'Cuerpo', footer: 'Pie de página' } as const

const REGION_OF = { header: 'del encabezado', body: 'del cuerpo', footer: 'del pie de página' } as const

function text(value: unknown): string {
  return issueParam(value, ', ')
}

/** 问题参数里的名字写成 «名字»。 */
function quoted(value: unknown): string {
  return `«${text(value)}»`
}

function columns(value: unknown): string {
  return `${text(value)} ${Number(value) === 1 ? 'columna' : 'columnas'}`
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`como mínimo ${text(params.min)}`)
  if (params.exclusiveMin !== undefined)
    parts.push(`mayor que ${text(params.exclusiveMin)}`)
  if (params.max !== undefined)
    parts.push(`como máximo ${text(params.max)}`)
  return parts.length === 0 ? 'Fuera del intervalo permitido' : `Debe ser ${parts.join(' y ')}`
}

