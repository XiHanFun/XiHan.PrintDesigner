const REGION_NAMES = { header: 'ヘッダー', body: '本文', footer: 'フッター' } as const

function text(value: unknown): string {
  return issueParam(value, '、')
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`${text(params.min)} 以上`)
  if (params.exclusiveMin !== undefined)
    parts.push(`${text(params.exclusiveMin)} より大きい`)
  if (params.max !== undefined)
    parts.push(`${text(params.max)} 以下`)
  return parts.length === 0 ? '値が範囲外です' : `${parts.join('、')}の値にしてください`
}

