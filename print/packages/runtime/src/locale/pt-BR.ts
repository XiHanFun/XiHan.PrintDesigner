const REGION_OF = { header: 'do cabeçalho', body: 'do corpo', footer: 'do rodapé' } as const

function text(value: unknown): string {
  return issueParam(value, ', ')
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`no mínimo ${text(params.min)}`)
  if (params.exclusiveMin !== undefined)
    parts.push(`maior que ${text(params.exclusiveMin)}`)
  if (params.max !== undefined)
    parts.push(`no máximo ${text(params.max)}`)
  return parts.length === 0 ? 'Fora do intervalo permitido' : `Deve ser ${parts.join(' e ')}`
}

