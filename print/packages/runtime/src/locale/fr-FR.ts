/** 区域名前带 de 与冠词的写法，如 de l’en-tête。 */
const REGION_OF = { header: 'de l’en-tête', body: 'du corps', footer: 'du pied de page' } as const

function text(value: unknown): string {
  return issueParam(value, ', ')
}

/** 法语的单复数：小于 2 取单数。 */
function plural(count: unknown, one: string, many: string): string {
  return Number(count) < 2 ? one : many
}

function range(params: Readonly<Record<string, unknown>>): string {
  const parts: string[] = []
  if (params.min !== undefined)
    parts.push(`au moins ${text(params.min)}`)
  if (params.exclusiveMin !== undefined)
    parts.push(`supérieure à ${text(params.exclusiveMin)}`)
  if (params.max !== undefined)
    parts.push(`au plus ${text(params.max)}`)
  return parts.length === 0 ? 'Valeur hors de la plage autorisée' : `Valeur hors de la plage autorisée (${parts.join(' et ')})`
}

